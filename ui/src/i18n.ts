export type StrKey = keyof typeof S;

export function t(lang: Lang, key: StrKey | string): string {
  const entry = (S as Record<string, readonly [string, string]>)[key];
  if (!entry) return key;
  return lang === "ms" ? entry[0] : entry[1];
}

export const MONTHS_MS = ["Januari", "Februari", "Mac", "April", "Mei", "Jun", "Julai", "Ogos", "September", "Oktober", "November", "Disember"];
export const MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

export function fmtDate(lang: Lang, iso?: string | null): string {
  if (!iso) return "-";
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  if (!y || !m || !d) return iso;
  return `${d} ${(lang === "ms" ? MONTHS_MS : MONTHS_EN)[m - 1]} ${y}`;
}
